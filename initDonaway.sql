-- -----------------------------------------------------
-- Modulo de Identificacion y Seguridad
-- -----------------------------------------------------

-- Tabla Ubicacion
CREATE TABLE IF NOT EXISTS UBICACION (
    ID_UBICACION INT AUTO_INCREMENT PRIMARY KEY,
    REGION ENUM ('NORTE','SUROESTE','SURESTE'),
    PROVINCIA VARCHAR(100), 
    CIUDAD_SECTOR VARCHAR(100),
    DIRECCION VARCHAR(100)
);

-- Tabla Institucion Medica
CREATE TABLE IF NOT EXISTS INSTITUCION_MEDICA (
    RNC_INSTITUCION VARCHAR(20) PRIMARY KEY,
    ID_INSTITUCION INT AUTO_INCREMENT UNIQUE,
    NOMBRE VARCHAR(255) NOT NULL,
    CONTACTO_EMERGENCIA VARCHAR(15),
    ID_UBICACION INT,
    
    FOREIGN KEY (ID_UBICACION) REFERENCES UBICACION(ID_UBICACION)
    );
    

-- Tabla Personal Medico
CREATE TABLE IF NOT EXISTS PERSONAL_MEDICO (
    CEDULA_PERSONAL VARCHAR(11) PRIMARY KEY,
    ID_PERSONAL INT AUTO_INCREMENT UNIQUE,
    RNC_INSTITUCION VARCHAR(20),
    NOMBRE VARCHAR(255) NOT NULL,
    FECHA_NACIMIENTO DATE,
    TELEFONO VARCHAR(15),
    EMAIL VARCHAR(100),
    CREDENCIALES_ENCRIPTADAS VARCHAR(255),
    FECHA_REGISTRO DATETIME DEFAULT CURRENT_TIMESTAMP,
    ULTIMO_ACCESO DATETIME,
    ROL ENUM('BIOANALISTA', 'ADMINISTRADOR', 'RECEPTOR'),
    FOREIGN KEY (RNC_INSTITUCION) REFERENCES INSTITUCION_MEDICA(RNC_INSTITUCION)
);

-- -----------------------------------------------------
-- Modulo Donante (Entidad Maestra)
-- -----------------------------------------------------

-- Tabla Donantes
CREATE TABLE IF NOT EXISTS DONANTES (
    CEDULA_DONANTE VARCHAR(11) PRIMARY KEY,
    ID_DONANTES INT AUTO_INCREMENT UNIQUE,
    NOMBRE_COMPLETO VARCHAR(255) NOT NULL,
    FECHA_NACIMIENTO DATE,
    SEXO ENUM('M', 'F'),
    TELEFONO VARCHAR(15),
    EMAIL VARCHAR(100),
    TIPO_SANGRE ENUM('A', 'B', 'AB', 'O') NOT NULL,
    FACTOR_RH ENUM('+', '-') NOT NULL,
    ESTADO_DISPONIBILIDAD ENUM('ACTIVO', 'DIFERIDO', 'EXCLUIDO'),
    AUTORIZACION_CONTACTO BOOLEAN DEFAULT FALSE,
    ULTIMA_DONACION DATETIME,
    ID_UBICACION INT,
    
    FOREIGN KEY (ID_UBICACION) REFERENCES UBICACION(ID_UBICACION)
);

-- -----------------------------------------------------
-- Modulo de Solicitud de Transfusion
-- -----------------------------------------------------

-- Tabla Receptor 
CREATE TABLE IF NOT EXISTS RECEPTOR (
    CEDULA_RECEPTOR VARCHAR(11) PRIMARY KEY,
	ID_RECEPTOR INT AUTO_INCREMENT UNIQUE,
    NOMBRE_COMPLETO VARCHAR(255),
    FECHA_NACIMIENTO DATE,
    SEXO ENUM('M', 'F'),
    TELEFONO VARCHAR(15),
    PESO INT,
    TIPO_SANGRE ENUM('A', 'B', 'AB', 'O'),
    FACTOR_RH ENUM('+', '-')
);

-- Tabla Solicutud para una Transfusion
CREATE TABLE IF NOT EXISTS SOLICITUD_TRANSFUSION (
    ID_SOLICITUD INT AUTO_INCREMENT PRIMARY KEY,
    CEDULA_RECEPTOR VARCHAR(11),
    RNC_INSTITUCION VARCHAR(20),
    FECHA_SOLICITUD DATETIME,
    PRIORIDAD ENUM('CRITICO', 'URGENTE', 'RUTINA'),
    ESTADO_SOLICITUD ENUM('PENDIENTE', 'EN CAMINO', 'ENTREGADA'),
    
    FOREIGN KEY (CEDULA_RECEPTOR) REFERENCES RECEPTOR(CEDULA_RECEPTOR),
    FOREIGN KEY (RNC_INSTITUCION) REFERENCES INSTITUCION_MEDICA(RNC_INSTITUCION)
);

-- -----------------------------------------------------
-- Modulo de Donaciones
-- -----------------------------------------------------

CREATE TABLE IF NOT EXISTS DONACION (
    ID_DONACION INT AUTO_INCREMENT PRIMARY KEY,
    CEDULA_DONANTE VARCHAR(11),
    CEDULA_RECEPTOR VARCHAR(11), -- (Para donaciones dirigidas)
    CEDULA_PERSONAL VARCHAR(11),
    RNC_INSTITUCION VARCHAR(20),
    FECHA_EXTRACCION DATETIME, 
    TIPO_DONACION ENUM('SANGRE TOTAL', 'AFERESIS'),
    TIPO_COMPONENTE ENUM('GLOBULOS ROJOS', 'PLAQUETAS', 'PLASMA'),
    
    FOREIGN KEY (CEDULA_DONANTE) REFERENCES DONANTES(CEDULA_DONANTE),
    FOREIGN KEY (CEDULA_RECEPTOR) REFERENCES RECEPTOR(CEDULA_RECEPTOR),
    FOREIGN KEY (CEDULA_PERSONAL) REFERENCES PERSONAL_MEDICO(CEDULA_PERSONAL),
    FOREIGN KEY (RNC_INSTITUCION) REFERENCES INSTITUCION_MEDICA(RNC_INSTITUCION)
);

-- Datos de Triaje
CREATE TABLE IF NOT EXISTS TRIAJE (
    ID_TRIAJE INT AUTO_INCREMENT PRIMARY KEY,
    ID_DONACION INT,
    PESO_LBS INT CHECK (PESO_LBS >= 110),
    PRESION_SISTOLICA INT NOT NULL CHECK (presion_sistolica BETWEEN 90 AND 180), 
    PRESION_DIASTOLICA INT NOT NULL CHECK (presion_diastolica BETWEEN 50 AND 100),
    PULSO INT NOT NULL CHECK (pulso BETWEEN 50 AND 100),
    TEMPERATURA_C DECIMAL(4,2) CHECK (TEMPERATURA_C BETWEEN 36.0 AND 37.2),
    HEMOGLOBINA DECIMAL(4,2) CHECK (hemoglobina BETWEEN 12.5 AND 20.0),

    FOREIGN KEY (ID_DONACION) REFERENCES DONACION(ID_DONACION)
);

-- Analisis de Laboratorio
CREATE TABLE IF NOT EXISTS ANALISIS_LAB (
    ID_ANALISIS INT AUTO_INCREMENT PRIMARY KEY,
    ID_DONACION INT,
    VIH BOOLEAN,
    HEPATITIS_B BOOLEAN,
    HEPATITIS_C BOOLEAN,
    SIFILIS BOOLEAN,
    CHAGAS BOOLEAN,
    NAT BOOLEAN,
    OTROS VARCHAR(100),
    
    FOREIGN KEY (ID_DONACION) REFERENCES DONACION(ID_DONACION)
);

-- -----------------------------------------------------
-- Modulo de Inventario
-- -----------------------------------------------------

-- Tabla del inventario (hemoderivados)
CREATE TABLE IF NOT EXISTS UNIDAD_HEMODERIVADO (
    ID_HEMODERIVADO INT AUTO_INCREMENT PRIMARY KEY,
    CODIGO_BARRAS VARCHAR(100) UNIQUE,
    ID_DONACION INT,
    RNC_INSTITUCION VARCHAR(20),
    CANTIDAD_PINTA INT, -- aprox 500ml
    FECHA_CADUCIDAD DATE,
    ESTADO_UNIDAD ENUM('DISPONIBLE', 'RESERVADA', 'DESCARTADA', 'ESPERA'),
    
    FOREIGN KEY (ID_DONACION) REFERENCES DONACION(ID_DONACION),
    FOREIGN KEY (RNC_INSTITUCION) REFERENCES INSTITUCION_MEDICA(RNC_INSTITUCION)
);



    
    
 
